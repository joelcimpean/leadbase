-- Release stale reservations and refresh the monthly plan-wallet on demand.
create or replace function public.leadbase_refresh_credit_period(p_user_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  acc public.ai_usage_accounts%rowtype;
  r public.ai_credit_reservations%rowtype;
  next_reset timestamptz;
begin
  insert into public.ai_usage_accounts (
    user_id, plan_id, subscription_status, monthly_credit_limit,
    plan_credit_balance, purchased_credit_balance, free_signup_credits_granted,
    monthly_token_limit, purchased_token_balance
  ) values (p_user_id, 'free', 'free', 0, 0, 50, true, 0, 0)
  on conflict (user_id) do nothing;

  select * into acc
  from public.ai_usage_accounts
  where user_id = p_user_id
  for update;

  -- Return expired reservations before calculating available balance.
  for r in
    select * from public.ai_credit_reservations
    where user_id = p_user_id
      and status = 'reserved'
      and expires_at <= now()
    for update
  loop
    update public.ai_usage_accounts
    set plan_credit_balance = plan_credit_balance + r.plan_credits_reserved,
        purchased_credit_balance = purchased_credit_balance + r.purchased_credits_reserved,
        updated_at = now()
    where user_id = p_user_id;

    update public.ai_credit_reservations
    set status = 'expired', settled_at = now()
    where id = r.id;
  end loop;

  select * into acc
  from public.ai_usage_accounts
  where user_id = p_user_id
  for update;

  -- A paid plan that is no longer active cannot keep spending plan credits.
  if acc.plan_id <> 'free' and acc.subscription_status not in ('active','trialing') then
    update public.ai_usage_accounts
    set plan_credit_balance = 0,
        updated_at = now()
    where user_id = p_user_id;
    return;
  end if;

  if acc.plan_id <> 'free'
     and acc.monthly_credit_limit > 0
     and acc.credit_period_resets_at is not null
     and acc.credit_period_resets_at <= now() then

    -- Reservations from the old month are released before the wallet reset.
    for r in
      select * from public.ai_credit_reservations
      where user_id = p_user_id and status = 'reserved'
      for update
    loop
      update public.ai_usage_accounts
      set plan_credit_balance = plan_credit_balance + r.plan_credits_reserved,
          purchased_credit_balance = purchased_credit_balance + r.purchased_credits_reserved,
          updated_at = now()
      where user_id = p_user_id;
      update public.ai_credit_reservations
      set status = 'expired', settled_at = now()
      where id = r.id;
    end loop;

    next_reset := acc.credit_period_resets_at;
    while next_reset <= now() loop
      next_reset := next_reset + interval '1 month';
    end loop;

    update public.ai_usage_accounts
    set plan_credit_balance = monthly_credit_limit,
        credit_period_started_at = next_reset - interval '1 month',
        credit_period_resets_at = next_reset,
        updated_at = now()
    where user_id = p_user_id;
  end if;
end;
$$;

create or replace function public.leadbase_reserve_credits(
  p_user_id uuid,
  p_request_key text,
  p_credits bigint,
  p_feature text,
  p_model text,
  p_metadata jsonb default '{}'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  acc public.ai_usage_accounts%rowtype;
  existing public.ai_credit_reservations%rowtype;
  use_plan bigint;
  use_purchased bigint;
begin
  if p_credits <= 0 then raise exception 'invalid credit reservation'; end if;
  perform public.leadbase_refresh_credit_period(p_user_id);

  select * into existing from public.ai_credit_reservations
  where user_id = p_user_id and request_key = p_request_key;
  if found then
    return jsonb_build_object('reserved_credits', existing.reserved_credits, 'status', existing.status);
  end if;

  select * into acc from public.ai_usage_accounts where user_id = p_user_id for update;
  if acc.credit_debt_balance > 0 then raise exception 'credit debt outstanding'; end if;
  if acc.plan_credit_balance + acc.purchased_credit_balance < p_credits then
    raise exception 'insufficient credits';
  end if;

  use_plan := least(acc.plan_credit_balance, p_credits);
  use_purchased := p_credits - use_plan;

  update public.ai_usage_accounts
  set plan_credit_balance = plan_credit_balance - use_plan,
      purchased_credit_balance = purchased_credit_balance - use_purchased,
      updated_at = now()
  where user_id = p_user_id;

  insert into public.ai_credit_reservations (
    user_id, request_key, feature, model, reserved_credits,
    plan_credits_reserved, purchased_credits_reserved, metadata
  ) values (
    p_user_id, p_request_key, coalesce(p_feature,'other'), p_model, p_credits,
    use_plan, use_purchased, coalesce(p_metadata,'{}'::jsonb)
  );

  return jsonb_build_object(
    'reserved_credits', p_credits,
    'plan_credits_reserved', use_plan,
    'purchased_credits_reserved', use_purchased,
    'status', 'reserved'
  );
end;
$$;

create or replace function public.leadbase_release_credit_reservation(
  p_user_id uuid,
  p_request_key text,
  p_reason text default 'released'
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  r public.ai_credit_reservations%rowtype;
begin
  select * into r from public.ai_credit_reservations
  where user_id = p_user_id and request_key = p_request_key
  for update;

  if not found or r.status <> 'reserved' then return; end if;

  update public.ai_usage_accounts
  set plan_credit_balance = plan_credit_balance + r.plan_credits_reserved,
      purchased_credit_balance = purchased_credit_balance + r.purchased_credits_reserved,
      updated_at = now()
  where user_id = p_user_id;

  update public.ai_credit_reservations
  set status = 'released',
      settled_at = now(),
      metadata = metadata || jsonb_build_object('releaseReason', p_reason)
  where id = r.id;
end;
$$;

create or replace function public.leadbase_settle_credit_reservation(
  p_user_id uuid,
  p_request_key text,
  p_actual_credits bigint,
  p_provider_cost_usd numeric,
  p_metadata jsonb default '{}'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  r public.ai_credit_reservations%rowtype;
  acc public.ai_usage_accounts%rowtype;
  consume_plan bigint := 0;
  consume_purchased bigint := 0;
  refund_plan bigint := 0;
  refund_purchased bigint := 0;
  extra bigint := 0;
  extra_plan bigint := 0;
  extra_purchased bigint := 0;
  shortfall bigint := 0;
  actual bigint := greatest(coalesce(p_actual_credits,0),0);
begin
  select * into r from public.ai_credit_reservations
  where user_id = p_user_id and request_key = p_request_key
  for update;

  if found and r.status = 'settled' then
    return jsonb_build_object('charged_credits', coalesce(r.actual_credits, actual), 'status', 'settled');
  end if;

  if not found or r.status <> 'reserved' then
    -- Reservation expired/released after the provider started. Charge directly.
    return public.leadbase_charge_credits(
      p_user_id, 'late:' || p_request_key, actual,
      coalesce(r.feature,'other'), r.model, p_provider_cost_usd,
      coalesce(p_metadata,'{}'::jsonb) || jsonb_build_object('lateSettlement', true)
    );
  end if;

  consume_plan := least(actual, r.plan_credits_reserved);
  consume_purchased := least(greatest(actual - consume_plan, 0), r.purchased_credits_reserved);
  refund_plan := r.plan_credits_reserved - consume_plan;
  refund_purchased := r.purchased_credits_reserved - consume_purchased;
  extra := greatest(actual - r.reserved_credits, 0);

  update public.ai_usage_accounts
  set plan_credit_balance = plan_credit_balance + refund_plan,
      purchased_credit_balance = purchased_credit_balance + refund_purchased,
      updated_at = now()
  where user_id = p_user_id;

  if extra > 0 then
    select * into acc from public.ai_usage_accounts where user_id = p_user_id for update;
    extra_plan := least(acc.plan_credit_balance, extra);
    extra_purchased := least(acc.purchased_credit_balance, extra - extra_plan);
    shortfall := extra - extra_plan - extra_purchased;

    update public.ai_usage_accounts
    set plan_credit_balance = plan_credit_balance - extra_plan,
        purchased_credit_balance = purchased_credit_balance - extra_purchased,
        credit_debt_balance = credit_debt_balance + shortfall,
        updated_at = now()
    where user_id = p_user_id;
  end if;

  update public.ai_credit_reservations
  set status = 'settled',
      actual_credits = actual,
      provider_cost_usd = greatest(coalesce(p_provider_cost_usd,0),0),
      metadata = metadata || coalesce(p_metadata,'{}'::jsonb),
      settled_at = now()
  where id = r.id;

  insert into public.ai_credit_transactions (
    user_id, amount, kind, source, request_key, provider_cost_usd, metadata
  ) values (
    p_user_id, -actual, 'usage', r.feature, 'settle:' || p_request_key,
    greatest(coalesce(p_provider_cost_usd,0),0),
    coalesce(p_metadata,'{}'::jsonb) || jsonb_build_object('model', r.model, 'debtCreated', shortfall)
  ) on conflict (user_id, request_key) where request_key is not null do nothing;

  return jsonb_build_object('charged_credits', actual, 'debt_created', shortfall, 'status', 'settled');
end;
$$;

create or replace function public.leadbase_charge_credits(
  p_user_id uuid,
  p_request_key text,
  p_credits bigint,
  p_feature text,
  p_model text,
  p_provider_cost_usd numeric,
  p_metadata jsonb default '{}'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  acc public.ai_usage_accounts%rowtype;
  existing_amount bigint;
  use_plan bigint := 0;
  use_purchased bigint := 0;
  shortfall bigint := 0;
  credits bigint := greatest(coalesce(p_credits,0),0);
begin
  select abs(amount) into existing_amount from public.ai_credit_transactions
  where user_id = p_user_id and request_key = p_request_key;
  if found then return jsonb_build_object('charged_credits', existing_amount, 'status', 'already_charged'); end if;

  perform public.leadbase_refresh_credit_period(p_user_id);
  select * into acc from public.ai_usage_accounts where user_id = p_user_id for update;

  use_plan := least(acc.plan_credit_balance, credits);
  use_purchased := least(acc.purchased_credit_balance, credits - use_plan);
  shortfall := credits - use_plan - use_purchased;

  update public.ai_usage_accounts
  set plan_credit_balance = plan_credit_balance - use_plan,
      purchased_credit_balance = purchased_credit_balance - use_purchased,
      credit_debt_balance = credit_debt_balance + shortfall,
      updated_at = now()
  where user_id = p_user_id;

  insert into public.ai_credit_transactions (
    user_id, amount, kind, source, request_key, provider_cost_usd, metadata
  ) values (
    p_user_id, -credits, 'usage', coalesce(p_feature,'other'), p_request_key,
    greatest(coalesce(p_provider_cost_usd,0),0),
    coalesce(p_metadata,'{}'::jsonb) || jsonb_build_object('model', p_model, 'debtCreated', shortfall)
  );

  return jsonb_build_object('charged_credits', credits, 'debt_created', shortfall, 'status', 'charged');
end;
$$;

create or replace function public.leadbase_grant_credits(
  p_user_id uuid,
  p_credits bigint,
  p_idempotency_key text,
  p_source text,
  p_metadata jsonb default '{}'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  acc public.ai_usage_accounts%rowtype;
  existing_amount bigint;
  credits bigint := greatest(coalesce(p_credits,0),0);
  debt_paid bigint := 0;
  wallet_added bigint := 0;
begin
  if credits <= 0 then raise exception 'invalid credit grant'; end if;

  select amount into existing_amount from public.ai_credit_transactions
  where user_id = p_user_id and request_key = p_idempotency_key;
  if found then return jsonb_build_object('granted_credits', existing_amount, 'status', 'already_granted'); end if;

  perform public.leadbase_refresh_credit_period(p_user_id);
  select * into acc from public.ai_usage_accounts where user_id = p_user_id for update;

  debt_paid := least(acc.credit_debt_balance, credits);
  wallet_added := credits - debt_paid;

  update public.ai_usage_accounts
  set credit_debt_balance = credit_debt_balance - debt_paid,
      purchased_credit_balance = purchased_credit_balance + wallet_added,
      updated_at = now()
  where user_id = p_user_id;

  insert into public.ai_credit_transactions (
    user_id, amount, kind, source, request_key, metadata
  ) values (
    p_user_id, credits, 'grant', p_source, p_idempotency_key,
    coalesce(p_metadata,'{}'::jsonb) || jsonb_build_object('debtPaid', debt_paid, 'walletAdded', wallet_added)
  );

  return jsonb_build_object('granted_credits', credits, 'debt_paid', debt_paid, 'wallet_added', wallet_added, 'status', 'granted');
end;
$$;


