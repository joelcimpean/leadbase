create or replace function public.leadbase_cost_guard_snapshot(p_user_id uuid)
returns jsonb
language sql
security definer
set search_path = public
as $$
  select jsonb_build_object(
    'user_day_usd', coalesce((select sum(provider_cost_usd) from public.ai_usage_events where user_id = p_user_id and created_at >= date_trunc('day', now() at time zone 'utc') at time zone 'utc'), 0),
    'global_day_usd', coalesce((select sum(provider_cost_usd) from public.ai_usage_events where created_at >= date_trunc('day', now() at time zone 'utc') at time zone 'utc'), 0),
    'global_month_usd', coalesce((select sum(provider_cost_usd) from public.ai_usage_events where created_at >= date_trunc('month', now() at time zone 'utc') at time zone 'utc'), 0)
  );
$$;

