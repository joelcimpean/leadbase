  export function getCampaignStatusLabel(
    status: string,
    language: AppLanguage
  ) {
    const labels: Record<
      string,
      {
        en: string;
        de: string;
      }
    > = {
      DRAFT: {
        en: "Draft",
        de: "Entwurf",
      },
  
      ACTIVE: {
        en: "Active",
        de: "Aktiv",
      },
  
      PAUSED: {
        en: "Paused",
        de: "Pausiert",
      },
  
      ARCHIVED: {
        en: "Archived",
        de: "Archiviert",
      },
    };
  
    return (
      labels[status]?.[
        language
      ] ??
      status
        .toLowerCase()
        .split("_")
        .map(
          (word) =>
            word
              .charAt(0)
              .toUpperCase() +
            word.slice(1)
        )
        .join(" ")
    );
  }
  
