  /* =========================================================
     TARGET ROLES
  ========================================================= */
  
  export function localizeTargetRoles(
    value: string | null,
    language: AppLanguage
  ) {
    if (
      !value ||
      language ===
        "en"
    ) {
      return value;
    }
  
    const roleMap: Record<
      string,
      string
    > = {
      owner:
        "Inhaber",
  
      "managing director":
        "Geschäftsführer",
  
      founder:
        "Gründer",
  
      ceo:
        "Geschäftsführer",
  
      director:
        "Geschäftsführer",
  
      geschäftsführer:
        "Geschäftsführer",
  
      inhaber:
        "Inhaber",
    };
  
    const roles =
      value
        .split(",")
        .map(
          (role) =>
            role.trim()
        )
        .filter(Boolean)
        .map(
          (role) =>
            roleMap[
              role.toLowerCase()
            ] ??
            role
        );
  
    return Array.from(
      new Set(
        roles
      )
    ).join(", ");
  }
  
